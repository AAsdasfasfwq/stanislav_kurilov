const named = (topoObj, names, tol, prec) => {
  const out = {};
  for (const g of topoObj.objects.countries.geometries) if (names.includes(g.properties.name)) {
    out[g.properties.name] = pack([T.feature(topoObj, g).geometry].filter(Boolean), { tol, prec, minPts: 4 });
  }
  return out;
};
