function dp(points, tol) { // Douglas-Peucker
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length); keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let maxD = 0, idx = -1;
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy);
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const d = L < 1e-6 ? Math.hypot(px - ax, py - ay) : Math.abs(dy * px - dx * py + bx * ay - by * ax) / L;
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return points.filter((_, i) => keep[i]);
}
const r = (v, k) => Math.round(v * k) / k;
function rings(geom) {
  const out = [];
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.type === 'MultiPolygon' ? geom.coordinates : [];
  for (const poly of polys) for (const ring of poly) out.push(ring);
  return out;
}
function pack(geoms, { tol, bbox, prec = 100, minPts = 4 }) {
  const res = [];
  for (const g of geoms) for (const ring of rings(g)) {
    if (bbox) {
      const inBox = ring.some(([x, y]) => x >= bbox[0] && x <= bbox[2] && y >= bbox[1] && y <= bbox[3]);
      if (!inBox) continue;
    }
    const s = dp(ring, tol);
    if (s.length < minPts) continue;
    res.push(s.map(([x, y]) => [r(x, prec), r(y, prec)]).flat());
  }
  return res;
}
